export function rulesAsPrompt(): string {
  return RULES.map(
    (r) =>
      `- ${r.id} [${r.group}] ${r.title}. Критичность по умолчанию: ${r.severity}. Источник: ${r.source}.\n  Что проверить: ${r.check}`,
  ).join("\n");
}
